function [B,A] = SanJiao_YingBianJuZhen(i,j,m)
%   三角单元应变矩阵 B=B(i结点坐标,j结点坐标,m结点坐标)
%   三角单元面积 A=A(i结点坐标,j结点坐标,m结点坐标)
%   注意坐标标号i-j-m为逆时针，输出为3*6矩阵

a=[1 i(1) i(2);1 j(1) j(2);1 m(1) m(2)];
A=0.5*det(a);
B=0.5/A*[j(2)-m(2) 0 m(2)-i(2) 0 i(2)-j(2) 0
    0 m(1)-j(1) 0 i(1)-m(1) 0 j(1)-i(1)
    m(1)-j(1) j(2)-m(2) i(1)-m(1) m(2)-i(2) j(1)-i(1) i(2)-j(2)];
end

